/**
 * The sign-in challenge message.
 *
 * Format and reasoning follow Sign-In With Ethereum (EIP-4361), minus the parts
 * that make sense for a chain with accounts and gas but not for a Solana
 * keypair. The goal is the same: the message a wallet displays must be
 * *specific* (which site, which wallet, which one-time value, when it expires)
 * so that a signature cannot be lifted from one context into another.
 *
 * A representative message:
 *
 *   adadive.example wants you to sign in with your Solana account:
 *   CHT55n175fUSewNo6kvDAUrGkT4S6bgRStDKTqNqMSpR
 *
 *   Sign in to the ADADIVE oracle backend and authorise deal mutations.
 *   A dispute raised after signing acts on the wallet's behalf.
 *
 *   URI: https://adadive.example
 *   Version: 1
 *   Chain ID: solana:localnet
 *   Nonce: 3f9a1c2e7b4d...
 *   Issued At: 2026-09-21T21:15:27.807Z
 *   Expiration Time: 2026-09-21T21:20:27.807Z
 *
 * Every field is load-bearing:
 *
 *   - **domain / URI** — so a signature obtained by a phishing site is not
 *     valid here, and vice versa. The verifier checks the domain matches what it
 *     issues.
 *   - **wallet address** — the message says who it is for; the verify step
 *     additionally requires the signing key to equal the challenge's wallet, so
 *     even a *valid* signature over someone else's message fails.
 *   - **nonce** — unique per challenge, so two sign-ins never share a message
 *     and a captured signature is not reusable. Single-use is enforced by the
 *     database, not by the nonce alone.
 *   - **issued at / expiration** — a bound on how long a signature is useful.
 *   - **statement** — the human-readable "what am I agreeing to", shown by the
 *     wallet. Deliberately says the signature authorises *mutations*, because
 *     that is what a session token can do.
 *
 * ## Canonicalisation
 *
 * The exact bytes matter, so this module is the only place the message is
 * built. The challenge is stored verbatim in `auth_challenges.message` and
 * verified against those stored bytes — never regenerated. Rebuilding the
 * message on verify would make a formatting change (a locale, a trailing
 * newline, key order) silently invalidate every outstanding challenge, and
 * worse, make two servers behind a load balancer with slightly different
 * versions disagree about what was signed.
 */

import { randomBytes } from "node:crypto";

/** The `solana:<cluster>` chain identifier, per CAIP-2. */
export type SolanaChainId = `solana:${string}`;

export interface ChallengeMessageParams {
  /** The site the challenge is being issued for (e.g. `adadive.example`). */
  domain: string;
  /** Canonical URI of the sign-in endpoint (e.g. `https://adadive.example`). */
  uri: string;
  /** The wallet address the challenge is issued to, in base58. */
  wallet: string;
  /** One-time nonce. Generated by `generateNonce` unless supplied. */
  nonce: string;
  /** When the challenge was issued. */
  issuedAt: Date;
  /** When the challenge stops being valid. */
  expiresAt: Date;
  /** `solana:localnet`, `solana:devnet`, `solana:mainnet-beta`, … */
  chainId: SolanaChainId;
  /** Human-readable statement of intent. */
  statement?: string;
  /** Protocol version label. Fixed at 1 for this phase. */
  version?: string;
}

export const DEFAULT_STATEMENT =
  "Sign in to the ADADIVE oracle backend and authorise deal mutations. " +
  "This signature does not move funds or approve a transaction.";

/**
 * A nonce with 256 bits of entropy.
 *
 * Random rather than a counter: a predictable nonce lets an attacker precompute
 * a message, and a nonce that repeats (across a restart, say) would let two
 * challenges share a message.
 *
 * Hex, not base64url: the SIWS grammar defines `message-nonce` as
 * `8*( ALPHA / DIGIT )`, and base64url emits `-` and `_` in roughly three of
 * every four 32-byte draws. Those characters are valid in the message *text*
 * but out of grammar, so a strict wallet parser (Phantom) can reject an
 * otherwise well-formed challenge. Hex is `[0-9a-f]` — always alphanumeric —
 * and still carries the full 256 bits.
 */
export function generateNonce(): string {
  return randomBytes(32).toString("hex");
}

/**
 * Build the exact message bytes a wallet is asked to sign.
 *
 * Line endings are `\n` and there is no trailing newline: the wallet signs
 * precisely this, and the verifier compares against the stored copy. Being
 * strict here is the point — a lenient message format is a format an attacker
 * can equivocate about.
 */
export function buildChallengeMessage(params: ChallengeMessageParams): string {
  const {
    domain,
    uri,
    wallet,
    nonce,
    issuedAt,
    expiresAt,
    chainId,
    statement = DEFAULT_STATEMENT,
    version = "1",
  } = params;

  return [
    `${domain} wants you to sign in with your Solana account:`,
    wallet,
    "",
    statement,
    "",
    `URI: ${uri}`,
    `Version: ${version}`,
    `Chain ID: ${chainId}`,
    `Nonce: ${nonce}`,
    `Issued At: ${issuedAt.toISOString()}`,
    `Expiration Time: ${expiresAt.toISOString()}`,
  ].join("\n");
}

/**
 * The message as UTF-8 bytes — what actually gets signed and verified.
 *
 * Callers should not reach for `Buffer.from(message)` themselves; going through
 * one function keeps the encoding decision in one place, which is the sort of
 * thing that is otherwise discovered by a failing signature in production.
 */
export function challengeMessageBytes(message: string): Uint8Array {
  return Buffer.from(message, "utf8");
}
